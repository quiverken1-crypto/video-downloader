'use strict';

const { BrowserWindow } = require('electron');
const path = require('node:path');
const fs = require('node:fs');
const { paths } = require('./paths.cjs');

function formatNetscapeCookies(cookies) {
  let output = '# Netscape HTTP Cookie File\n# Generated by Multi-Platform Downloader\n\n';
  for (const c of cookies) {
    let domain = c.domain || '';
    if (domain && !domain.startsWith('.')) domain = '.' + domain;
    const flag = domain.startsWith('.') ? 'TRUE' : 'FALSE';
    const cookiePath = c.path || '/';
    const secure = c.secure ? 'TRUE' : 'FALSE';
    const expiration = c.expirationDate ? Math.round(c.expirationDate) : 0;
    const name = c.name;
    const value = c.value;
    output += `${domain}\t${flag}\t${cookiePath}\t${secure}\t${expiration}\t${name}\t${value}\n`;
  }
  return output;
}

function mergeAndSaveCookies(newCookies, filePath) {
  const netscapeContent = formatNetscapeCookies(newCookies);
  fs.mkdirSync(path.dirname(filePath), { recursive: true });
  fs.writeFileSync(filePath, netscapeContent, 'utf8');
}

