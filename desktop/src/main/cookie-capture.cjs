function openLoginCaptureWindow(platformKey = 'bilibili', parentWindow = null) {
  const config = PLATFORM_LOGIN_CONFIGS[platformKey] || PLATFORM_LOGIN_CONFIGS.bilibili;

  return new Promise((resolve) => {
    let captured = false;
    let authWindow = new BrowserWindow({
      width: 540,
      height: 740,
      parent: parentWindow || undefined,
      modal: Boolean(parentWindow),
      title: `[登录获取凭证] 请登录 ${config.name}（登录成功将自动保存并关闭）`,
      backgroundColor: '#111820',
      autoHideMenuBar: true,
      webPreferences: {
        partition: 'persist:downloader_auth',
        contextIsolation: true,
        nodeIntegration: false,
        sandbox: true,
      },
    });

    const authSession = authWindow.webContents.session;

    const checkCookies = async () => {
      if (captured || authWindow.isDestroyed()) return;
      try {
        const cookies = await authSession.cookies.get({});
        if (config.checkSuccess(cookies)) {
          captured = true;
          mergeAndSaveCookies(cookies, paths.cookieFile);
          authWindow.setTitle(`✅ ${config.name} 登录成功！正在保存 Cookie...`);
          setTimeout(() => {
            if (!authWindow.isDestroyed()) authWindow.close();
            resolve({ ok: true, platform: platformKey, platformName: config.name, count: cookies.length });
          }, 800);
        }
      } catch (err) {
        console.error('Error checking cookies:', err);
      }
    };

    authWindow.webContents.on('did-navigate', checkCookies);
    authWindow.webContents.on('did-finish-load', checkCookies);

    const timer = setInterval(checkCookies, 1200);

    authWindow.on('closed', () => {
      clearInterval(timer);
      authWindow = null;
      if (!captured) {
        resolve({ ok: false, message: '用户取消了登录窗口' });
      }
    });

    authWindow.loadURL(config.loginUrl);
  });
}

module.exports = { openLoginCaptureWindow, PLATFORM_LOGIN_CONFIGS };
